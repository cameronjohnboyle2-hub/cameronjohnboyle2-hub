const fs=require('fs'),path=require('path'),vm=require('vm');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
function build(){
  let html=read('classroom/ui.template.html');
  // Use the exact same tactical controller as the perpetual plugin. The finite
  // adapter has its own UI, so the shared code gets no legacy DOM elements.
  const tactics = '/* Generated from figma-plugin/ui-controller.js */\n' +
    '(function (root) {\n' +
    '  function createClassroomTactics(classroomHooks) {\n' +
    '    const document = { getElementById: () => null };\n' +
    '    const Math = Object.create(globalThis.Math);\n' +
    '    if (classroomHooks.random) Math.random = classroomHooks.random;\n' +
    read('figma-plugin/ui-controller.js') +
    '\n    return getClassroomTactics();\n  }\n' +
    '  if (typeof module === "object" && module.exports) module.exports = createClassroomTactics;\n' +
    '  else root.createClassroomTactics = createClassroomTactics;\n' +
    '})(globalThis);\n';
  const sources={SETTINGS:read('engine/settings.js'),CORE:read('engine/core.js'),TACTICS:tactics,BATTLE:read('engine/classroom.js'),CONTROLLER:read('classroom/ui-controller.js')};
  for(const [key,source]of Object.entries(sources)){const token='/* __CLASSROOM_'+key+'__ */';if(html.split(token).length!==2)throw Error('Expected one '+token);html=html.replace(token,()=>source.replace(/<\/script/gi,'<\\/script'));}
  for(const m of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi))new vm.Script(m[1]);
  const original=read('figma-plugin/perpetual-main.js'),bridge=read('classroom/bridge.js');
  const main='// Generated by scripts/build-classroom.cjs. Perpetual source is preserved in perpetual-main.js.\n'+
    'if (figma.command === "classroom") {\n'+bridge+'\nfigma.showUI('+JSON.stringify(html)+', {width:460,height:760,themeColors:true});\nClassroomBridge.create(figma);\n} else {\n'+original+'\n}\n';
  new vm.Script(main);
  fs.writeFileSync(path.join(root,'classroom/tactics.js'),tactics);
  fs.writeFileSync(path.join(root,'figma-plugin/code.js'),main);fs.writeFileSync(path.join(root,'classroom/preview.html'),html);
  console.log('[PASS] Classroom bundle; preserved perpetual entry ('+Buffer.byteLength(main)+' bytes).');
}
if(require.main===module)build();module.exports={build};
